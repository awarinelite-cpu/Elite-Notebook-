// A Drive connection that is intentionally separate from the app's Google
// sign-in (Firebase Auth). It uses Google Identity Services' OAuth2 token
// client directly, so connecting/disconnecting Drive never touches the
// signed-in app account — the two can be different Google accounts.
//
// On the native Android app, this instead goes through DriveAuthPlugin
// (Play Services' native Authorization API — see driveAuthNative.js), since
// Google blocks OAuth sign-in inside embedded WebViews and caps how many
// accounts a WebView session can show at once. The web/browser flow below
// is kept as a fallback for running this as a plain PWA in a real browser.
//
// Requires VITE_GOOGLE_CLIENT_ID — the "Web client ID" already generated by
// Firebase under Authentication → Sign-in method → Google → Web SDK
// configuration (Google Cloud Console → APIs & Services → Credentials for
// the same project also shows it). No new OAuth app needs to be created.
// The native Android path additionally requires a separate "Android" type
// OAuth client registered with this app's package name + SHA-1 fingerprint
// (see DriveAuthPlugin.java) — Google matches that by signature, not by ID.
//
// Multiple Google accounts can be linked at once — each keeps its own
// access token, keyed by email. One of them is "active" (the one whose
// files are shown), but all of them stay connected so copy/move can pull
// from one and push to another.

import { Capacitor } from '@capacitor/core'
import { authorizeDriveNative } from './driveAuthNative.js'

// drive.readonly alone can't create folders or upload files. drive.file
// would only let us write into files/folders this app itself created, not
// into arbitrary existing folders the person browses to — so full `drive`
// is needed to upload into any folder they navigate to in-app.
const SCOPE = 'https://www.googleapis.com/auth/drive openid email profile'
const SCOPE_VERSION = 2 // bump whenever SCOPE changes, to force existing sessions to reconnect
const ACCOUNTS_KEY = 'elite-notebook:drive-accounts'
const ACTIVE_KEY = 'elite-notebook:drive-active-account'
const LEGACY_SINGLE_KEY = 'elite-notebook:drive-session' // pre-multi-account format
const CLIENT_ID = import.meta.env.VITE_GOOGLE_CLIENT_ID

let scriptPromise = null

function loadScript() {
  if (scriptPromise) return scriptPromise
  scriptPromise = new Promise((resolve, reject) => {
    if (window.google?.accounts?.oauth2) {
      resolve()
      return
    }
    const s = document.createElement('script')
    s.src = 'https://accounts.google.com/gsi/client'
    s.async = true
    s.defer = true
    s.onload = () => resolve()
    s.onerror = () => reject(new Error('Failed to load Google Identity Services'))
    document.head.appendChild(s)
  })
  return scriptPromise
}

// Accounts are keyed by email (a Google account's email is a stable,
// natural id — and it means adding the same account twice just refreshes
// its token instead of creating a duplicate entry).
export function loadDriveAccounts() {
  try {
    const raw = localStorage.getItem(ACCOUNTS_KEY)
    if (raw) {
      const accounts = JSON.parse(raw)
      return accounts.filter((a) => a.scopeVersion === SCOPE_VERSION)
    }
    // Migrate a pre-multi-account session, if one exists.
    const legacyRaw = localStorage.getItem(LEGACY_SINGLE_KEY)
    if (legacyRaw) {
      const legacy = JSON.parse(legacyRaw)
      localStorage.removeItem(LEGACY_SINGLE_KEY)
      if (legacy.scopeVersion === SCOPE_VERSION && legacy.email) {
        saveDriveAccounts([legacy])
        return [legacy]
      }
    }
    return []
  } catch {
    return []
  }
}

export function saveDriveAccounts(accounts) {
  localStorage.setItem(ACCOUNTS_KEY, JSON.stringify(accounts))
}

export function loadActiveAccountEmail() {
  return localStorage.getItem(ACTIVE_KEY) || null
}

export function saveActiveAccountEmail(email) {
  if (email) localStorage.setItem(ACTIVE_KEY, email)
  else localStorage.removeItem(ACTIVE_KEY)
}

async function fetchEmail(accessToken) {
  try {
    const res = await fetch('https://www.googleapis.com/oauth2/v2/userinfo', {
      headers: { Authorization: `Bearer ${accessToken}` },
    })
    if (!res.ok) return null
    const data = await res.json()
    return data
  } catch {
    return null
  }
}


// A TWA (installed Chrome-based Android app) is not a Capacitor native app, so
// it takes the web flow — but Google's token popup can't open there, and its
// callbacks never fire, leaving the UI stuck on "Connecting…". In that case we
// use a full-page OAuth redirect instead (implicit flow, token in the URL hash).
export function isTwa() {
  if (Capacitor.isNativePlatform()) return false
  try {
    if (document.referrer && document.referrer.startsWith('android-app://')) return true
    return !!window.matchMedia?.('(display-mode: standalone)').matches
  } catch {
    return false
  }
}

const OAUTH_STATE_KEY = 'elite-notebook:drive-oauth-state'

function startRedirectAuth({ loginHint, selectAccount }) {
  const state = Math.random().toString(36).slice(2) + Date.now().toString(36)
  localStorage.setItem(OAUTH_STATE_KEY, state)
  const params = new URLSearchParams({
    client_id: CLIENT_ID,
    redirect_uri: window.location.origin + '/',
    response_type: 'token',
    scope: SCOPE,
    include_granted_scopes: 'true',
    state,
    prompt: loginHint ? 'consent' : selectAccount ? 'select_account consent' : 'consent',
  })
  if (loginHint) params.set('login_hint', loginHint)
  window.location.assign('https://accounts.google.com/o/oauth2/v2/auth?' + params.toString())
  // Page navigates away; never resolve.
  return new Promise(() => {})
}

// Call once on startup. If the URL hash carries an OAuth redirect result,
// turns it into a Drive session (and cleans the URL). Returns null otherwise.
export async function consumeRedirectResult() {
  const hash = window.location.hash
  if (!hash || !hash.includes('state=')) return null
  const p = new URLSearchParams(hash.replace(/^#/, ''))
  const expected = localStorage.getItem(OAUTH_STATE_KEY)
  if (!expected || p.get('state') !== expected) return null
  localStorage.removeItem(OAUTH_STATE_KEY)
  history.replaceState(null, '', window.location.pathname + window.location.search)
  const token = p.get('access_token')
  if (!token) return null
  const profile = await fetchEmail(token)
  return {
    accessToken: token,
    expiresAt: Date.now() + (Number(p.get('expires_in')) || 3300) * 1000,
    email: profile?.email || null,
    name: profile?.name || null,
    picture: profile?.picture || null,
    scopeVersion: SCOPE_VERSION,
  }
}

function withTimeout(promise, ms) {
  let t
  const timeout = new Promise((_, reject) => { t = setTimeout(() => reject(new Error('timeout')), ms) })
  return Promise.race([promise, timeout]).finally(() => clearTimeout(t))
}

const NATIVE_SCOPES = ['https://www.googleapis.com/auth/drive', 'email', 'profile']

async function requestDriveTokenNative() {
  const accessToken = await authorizeDriveNative(NATIVE_SCOPES)
  const profile = await fetchEmail(accessToken)
  return {
    accessToken,
    // Play Services access tokens are typically valid ~1 hour; there's no
    // expires_in returned by the native Authorization API, so this is a
    // conservative estimate. A 401 from the Drive API triggers a fresh
    // authorize() call regardless (see useDriveAuth's reconnect-on-401).
    expiresAt: Date.now() + 55 * 60 * 1000,
    email: profile?.email || null,
    name: profile?.name || null,
    picture: profile?.picture || null,
    scopeVersion: SCOPE_VERSION,
  }
}

// interactive=true shows the account picker/consent popup.
// interactive=false tries a silent, no-popup refresh using the browser's
// existing Google session — this is what lets Drive "stay connected" after
// closing and reopening the app, without asking the person to sign in again.
// selectAccount=true forces Google's account chooser even if the browser
// already has a Google session — this is how "add another account" lets
// someone pick a *different* account than the one already linked.
//
// loginHint and selectAccount only apply to the web/WebView flow — the
// native flow always shows Play Services' own full, uncapped account
// chooser when a picker is needed, and resolves silently on its own when
// the scope is already granted, so there's no separate "hint" concept.
export function requestDriveToken({ interactive = true, loginHint, selectAccount = false } = {}) {
  if (Capacitor.isNativePlatform()) {
    return requestDriveTokenNative()
  }
  if (isTwa()) {
    // No silent refresh possible without a popup; the UI shows Reconnect instead.
    if (!interactive) return Promise.reject(new Error('silent-unsupported'))
    if (!CLIENT_ID) return Promise.reject(new Error('missing-client-id'))
    return startRedirectAuth({ loginHint, selectAccount })
  }
  // Timeout so a popup that never reports back can't leave "Connecting…" stuck.
  return withTimeout(loadScript().then(
    () =>
      new Promise((resolve, reject) => {
        if (!CLIENT_ID) {
          reject(new Error('missing-client-id'))
          return
        }
        const client = window.google.accounts.oauth2.initTokenClient({
          client_id: CLIENT_ID,
          scope: SCOPE,
          callback: async (resp) => {
            if (resp.error) {
              reject(new Error(resp.error))
              return
            }
            const profile = await fetchEmail(resp.access_token)
            const session = {
              accessToken: resp.access_token,
              expiresAt: Date.now() + (Number(resp.expires_in) || 3300) * 1000,
              email: profile?.email || loginHint || null,
              name: profile?.name || null,
              picture: profile?.picture || null,
              scopeVersion: SCOPE_VERSION,
            }
            resolve(session)
          },
          error_callback: (err) => reject(new Error(err?.type || 'popup_failed')),
        })
        client.requestAccessToken({
          // A specific hint means "go straight to this account" — forcing
          // select_account on top of that re-shows the full chooser anyway
          // (Google always renders it when select_account is present,
          // hint or not), which is what was surfacing every linked account
          // — and hitting Google's max-signed-in-accounts wall — even when
          // a single email was typed in. Only fall back to the full
          // chooser when there's no hint to target.
          prompt: loginHint ? 'consent' : selectAccount ? 'select_account consent' : interactive ? 'consent' : '',
          hint: loginHint || undefined,
        })
      })
  ), interactive ? 120000 : 10000)
}
